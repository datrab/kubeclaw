import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const checkMode = process.argv.includes('--check');
const jsonOutputPath = path.join(
  root,
  'docs/generated/inventory/plugin-system.json',
);
const markdownOutputPath = path.join(
  root,
  'docs/architecture/plugin-system-current-inventory.md',
);
const packageRoots = [
  'skills/common/plugins',
  'skills/nova/plugins',
  'skills/buster/plugins',
];
const runtimeRoot = 'skills/common/plugin-runtime';

function filesBelow(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name))
    .flatMap((entry) => {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) return filesBelow(entryPath);
      return entry.isFile() ? [entryPath] : [];
    });
}

function relative(filePath) {
  return path.relative(root, filePath).split(path.sep).join('/');
}

const manifestPaths = packageRoots
  .flatMap((packageRoot) => filesBelow(path.join(root, packageRoot)))
  .filter((filePath) =>
    ['plugin.json', 'openclaw.plugin.json'].includes(path.basename(filePath)))
  .sort();

const packages = manifestPaths.map((manifestPath) => {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const packageRoot = path.dirname(manifestPath);
  const pipeline = path.basename(manifestPath) === 'plugin.json';
  const registrations = pipeline
    ? [
        ...(manifest.stages ?? []).map((registration) => ({
          kind: 'stage',
          id: registration.id,
        })),
        ...(manifest.observers ?? []).map((registration) => ({
          kind: 'observer',
          id: registration.id,
        })),
        ...(manifest.adapters ?? []).map((registration) => ({
          kind: 'adapter',
          id: registration.id,
        })),
      ]
    : [];
  return {
    id: manifest.id,
    version: manifest.packageVersion ?? manifest.version ?? null,
    kind: pipeline ? 'pipeline-plugin' : 'openclaw-plugin',
    root: relative(packageRoot),
    manifest: relative(manifestPath),
    files: filesBelow(packageRoot)
      .filter((filePath) => !filePath.includes(`${path.sep}node_modules${path.sep}`))
      .map(relative),
    registrations,
  };
});

const registrations = packages.flatMap((pluginPackage) =>
  pluginPackage.registrations.map((registration) => ({
    ...registration,
    packageId: pluginPackage.id,
    registrationId: `${pluginPackage.id}:${registration.id}`,
  })));
const runtimeFiles = filesBelow(path.join(root, runtimeRoot))
  .filter((filePath) =>
    !filePath.includes(`${path.sep}node_modules${path.sep}`) &&
    !filePath.includes(`${path.sep}dist${path.sep}`))
  .map(relative);
const allFiles = [
  ...new Set([
    ...runtimeFiles,
    ...packages.flatMap((pluginPackage) => pluginPackage.files),
  ]),
].sort();
const counts = {
  packages: packages.filter((pluginPackage) =>
    pluginPackage.kind === 'pipeline-plugin').length,
  packageRoots: packages.length,
  stages: registrations.filter((item) => item.kind === 'stage').length,
  observers: registrations.filter((item) => item.kind === 'observer').length,
  adapters: registrations.filter((item) => item.kind === 'adapter').length,
  registrations: registrations.length,
  files: allFiles.length,
};
const inventory = {
  schemaVersion: 'plugin-system-inventory-v2',
  generatedBy: 'scripts/plugin-system-inventory.mjs',
  summary: counts,
  runtime: { root: runtimeRoot, files: runtimeFiles },
  packages,
  registrations,
  files: allFiles,
};
const json = `${JSON.stringify(inventory, null, 2)}\n`;
const markdown = `# Plugin System Inventory

Status: generated canonical v2 inventory

Generated by \`scripts/plugin-system-inventory.mjs\`.

## Summary

- Pipeline packages: ${counts.packages}
- Discovered package roots: ${counts.packageRoots}
- Registrations: ${counts.registrations}
  - Stages: ${counts.stages}
  - Observers: ${counts.observers}
  - Adapters: ${counts.adapters}
- Runtime and package files: ${counts.files}

## Packages

${packages.map((pluginPackage) =>
  `- \`${pluginPackage.id}\` (${pluginPackage.kind}, ${pluginPackage.registrations.length} registrations) — \`${pluginPackage.root}\``).join('\n')}
`;

function verifyOrWrite(filePath, expected) {
  if (checkMode) {
    if (!fs.existsSync(filePath) || fs.readFileSync(filePath, 'utf8') !== expected) {
      throw new Error(
        `Plugin-system inventory is stale: ${relative(filePath)}. `
        + 'Run: npm run plugin-system:inventory',
      );
    }
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, expected);
}

try {
  verifyOrWrite(jsonOutputPath, json);
  verifyOrWrite(markdownOutputPath, markdown);
  console.log(
    `${checkMode ? 'verified' : 'generated'} plugin-system inventory `
    + `(${counts.packageRoots} roots, ${counts.registrations} registrations)`,
  );
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
