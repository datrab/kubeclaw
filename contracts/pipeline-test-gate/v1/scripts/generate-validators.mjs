import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const schema = JSON.parse(fs.readFileSync(new URL('schemas/pipeline-test-gate.v1.schema.json', root), 'utf8'));
const e2eText = fs.readFileSync(new URL('schemas/e2e-result.v1.schema.json', root), 'utf8');
const e2e = JSON.parse(e2eText);
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
ajv.addSchema(schema);
ajv.addSchema(e2e);
const names = Object.keys(schema.$defs);
const exports = Object.fromEntries(names.map((name, index) => [`contractValidator${index}`, `${schema.$id}#/$defs/${name}`]));
exports.validateE2e = e2e.$id;
// Bundle the exact AJV runtime helpers, rather than granting stages filesystem,
// dynamic compiler, or package-root access. All original schemas remain authoritative.
const entry = standaloneCode(ajv, exports)
  + `\nexport const schemaValidators = {${names.map((name, index) => `${JSON.stringify(name)}: contractValidator${index}`).join(',')}};`
  + `\nexport const e2eSchemaDigest = ${JSON.stringify('sha256:' + crypto.createHash('sha256').update(e2eText).digest('hex'))};`;
const result = await build({ stdin: { contents: entry, resolveDir: fileURLToPath(root), sourcefile: 'canonical-validators.mjs', loader: 'js' },
  bundle: true, platform: 'neutral', format: 'esm', write: false, legalComments: 'inline' });
// AJV helper .code strings are compiler metadata, not runtime validation.
// They are unnecessary after standalone compilation and bundling.
const generated = result.outputFiles[0].text.replace(/^\s*(?:ucs2length|equal)\.code = [^\n]+;$/gmu, '');
if (/\b(?:eval|Function|require)\s*\(/u.test(generated)) throw new Error('Generated validator must be static and CSP-safe: ' + generated.match(/.{0,60}\b(?:eval|Function|require)\s*\(.{0,120}/gu)?.join('\n'));
fs.writeFileSync(new URL('src/validators.generated.mjs', root), '// Generated by scripts/generate-validators.mjs; do not edit.\n' + generated);
fs.writeFileSync(new URL('src/validators.generated.d.mts', root), `export type Validator = ((value: unknown) => boolean) & { errors?: unknown[] | null };\nexport const schemaValidators: Readonly<Record<string, Validator>>;\nexport const validateE2e: Validator;\nexport const e2eSchemaDigest: string;\n`);
