import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemasRoot = path.join(packageRoot, "schemas");
const outputPath = path.join(packageRoot, "src", "validators.generated.mjs");

const readSchema = (name) =>
  JSON.parse(fs.readFileSync(path.join(schemasRoot, name), "utf8"));

const prismSchema = readSchema("prism-v1.schema.json");
const baselineV2 = readSchema("baseline-v2.schema.json");
const engineRequests = readSchema("engine-requests.v1.json");
const engineResults = readSchema("engine-results.v1.json");

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true },
});
addFormats(ajv);
ajv.addSchema(prismSchema);
ajv.addSchema(baselineV2);
ajv.addSchema(engineRequests);
ajv.addSchema(engineResults);

const prismNames = [
  "designRequest",
  "designDocument",
  "operation",
  "baselineManifest",
  "acceptanceCriteria",
  "previewIndex",
  "preferenceEvent",
  "retrievalQuery",
];
const engineNames = ["generate", "render", "evaluate", "ingest", "publish"];
const upperFirst = (value) => `${value[0].toUpperCase()}${value.slice(1)}`;
const validators = {};
validators.validateBaselineManifestV2 = baselineV2.$id;

for (const name of prismNames) {
  validators[`validate${upperFirst(name)}`] =
    `${prismSchema.$id}#/$defs/${name}`;
}
for (const name of engineNames) {
  validators[`validateEngineRequest${upperFirst(name)}`] =
    `${engineRequests.$id}#/$defs/${name}`;
  validators[`validateEngineResult${upperFirst(name)}`] =
    `${engineResults.$id}#/$defs/${name}`;
}

const generated = standaloneCode(ajv, validators)
  .replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/u,
    'import ucs2LengthModule from "ajv/dist/runtime/ucs2length.js";const $1 = ucs2LengthModule.default;',
  )
  .replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/u,
    'import equalModule from "ajv/dist/runtime/equal.js";const $1 = equalModule.default;',
  )
  .replace(
    /const (\w+) = require\("ajv-formats\/dist\/formats"\)\.fullFormats\["date-time"\];/u,
    'import formatsModule from "ajv-formats/dist/formats.js";const $1 = formatsModule.fullFormats["date-time"];',
  );
if (/\b(?:eval|Function)\s*\(/u.test(generated) || /\brequire\s*\(/u.test(generated)) {
  throw new Error("generated Prism validators are not browser CSP-safe");
}

fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-validators.mjs. Do not edit.\n${generated}`,
);
